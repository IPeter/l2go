// Config is the whole configuration file. Login and game servers read the
// same file.
type Config struct {
	// Comment is free text for people reading the file. It is ignored.
	Comment     string       `json:"_comment,omitempty"`
	LoginServer LoginServer  `json:"loginserver"`
	GameServers []GameServer `json:"gameservers"`

	// Path is the file the config was loaded from, or empty for the
	// built-in defaults.
	Path string `json:"-"`
}

// LoginServer configures the login server.
type LoginServer struct {
	Comment string `json:"_comment,omitempty"`
	// Host is where game servers reach the login server.
	Host string `json:"host"`
	// ClientListen is the listen address for game clients.
	ClientListen string `json:"clientListen"`
	// GameServerListen is the listen address for game server links.
	GameServerListen string `json:"gameServerListen"`
	// AutoCreate creates an account on the first login with a new username.
	AutoCreate bool `json:"autoCreate"`
	// InternalNetworks lists client networks (CIDR) that get a game server's
	// InternalIP in the server list. Everyone else gets its ExternalIP.
	InternalNetworks []string `json:"internalNetworks"`
	Database         Database `json:"database"`
	// RSAKeyPairs is the number of RSA key pairs generated at startup for
	// the login handshake. Each connection picks one at random.
	RSAKeyPairs int `json:"rsaKeyPairs"`
	// SessionTTL is how long session keys stay valid after a login, for
	// example "2m".
	SessionTTL Duration `json:"sessionTTL"`
}

// GameServer configures one game server.
type GameServer struct {
	Comment string `json:"_comment,omitempty"`
	// ID identifies the server in the server list and on the command line
	// (1-255).
	ID   int    `json:"id"`
	Name string `json:"name"`
	// Secret authenticates the game server to the login server on the
	// link (an HMAC challenge; the secret itself is never sent). Both
	// servers read it from the same file.
	Secret string `json:"secret"` //nolint:gosec // read from the config file, never sent
	// InternalIP is announced to clients from InternalNetworks, ExternalIP
	// to everyone else. Both must be IPv4.
	InternalIP string `json:"internalIP"`
	ExternalIP string `json:"externalIP"`
	// Port is both the listen port and the port announced to clients.
	Port     int      `json:"port"`
	Database Database `json:"database"`
	Options  Options  `json:"options"`
	Scripts  Scripts  `json:"scripts"`
	// AllowedProtocols are the client protocol versions accepted.
	AllowedProtocols []int32 `json:"allowedProtocols"`
	// DataDir is the game data folder (generated by cmd/datagen). The NPC
	// dialogs are in its html subfolder.
	DataDir string `json:"dataDir"`
	// MaxCharactersPerAccount limits characters per account (0 = no limit).
	MaxCharactersPerAccount int `json:"maxCharactersPerAccount"`

	// World, Chat, NPCs, Geodata, Items, Economy, Rates, Combat and PvP are
	// the game rules. A section or a field left out of the file keeps its
	// default (see DefaultWorld, DefaultChat, DefaultNPCs, DefaultItems,
	// DefaultEconomy, DefaultRates, DefaultCombat and DefaultPvP).
	World   World   `json:"world"`
	Chat    Chat    `json:"chat"`
	NPCs    NPCs    `json:"npcs"`
	Geodata Geodata `json:"geodata"`
	Items   Items   `json:"items"`
	Economy Economy `json:"economy"`
	Rates   Rates   `json:"rates"`
	Combat  Combat  `json:"combat"`
	PvP     PvP     `json:"pvp"`
}

// UnmarshalJSON decodes a game server on top of the default game rule
// sections, so that fields left out keep their defaults while explicit
// false and 0 values are kept. Unknown fields are an error.
func (g *GameServer) UnmarshalJSON(b []byte) error {
	type plain GameServer // without this method
	p := plain{
		World:   DefaultWorld(),
		Chat:    DefaultChat(),
		NPCs:    DefaultNPCs(),
		Items:   DefaultItems(),
		Economy: DefaultEconomy(),
		Rates:   DefaultRates(),
		Combat:  DefaultCombat(),
		PvP:     DefaultPvP(),
	}
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&p); err != nil {
		return err
	}
	*g = GameServer(p)
	return nil
}

// World configures the world loop and character persistence.
type World struct {
	Comment string `json:"_comment,omitempty"`
	// TickInterval is the world loop's tick, for example "100ms".
	TickInterval Duration `json:"tickInterval"`
	// AutosaveInterval is how often the players in the world are saved, for
	// example "15m". 0 turns periodic saving off; players are still saved
	// when they leave the world (Mobius CharacterDataStoreInterval).
	AutosaveInterval Duration `json:"autosaveInterval"`
	// DeleteCharAfterDays is how long a character marked for deletion
	// stays restorable. 0 deletes characters at once, as the Mobius code
	// does (its Player.ini comment says 0 disallows deletion; the code
	// deletes immediately).
	DeleteCharAfterDays int `json:"deleteCharAfterDays"`
	// MaxRunSpeed caps the run speed of players (Mobius MaxRunSpeed).
	MaxRunSpeed int `json:"maxRunSpeed"`
	// SpawnProtection is how long a player that entered the world is safe
	// from aggressive monsters, until its first action, for example "10m".
	// 0 turns it off (Mobius PlayerSpawnProtection).
	SpawnProtection Duration `json:"spawnProtection"`
	// GridsAlwaysOn keeps every world region active, so monsters think
	// even where no player is (Mobius GridsAlwaysOn).
	GridsAlwaysOn bool `json:"gridsAlwaysOn"`
	// GridTurnOnTime is the delay before the neighbours of a region a player
	// entered become active, for example "1s" (Mobius
	// GridNeighborTurnOnTime).
	GridTurnOnTime Duration `json:"gridTurnOnTime"`
	// GridTurnOffTime is the delay before regions with no player around
	// become inactive, for example "90s" (Mobius GridNeighborTurnOffTime).
	GridTurnOffTime Duration `json:"gridTurnOffTime"`
}

// DefaultWorld returns the Mobius defaults.
func DefaultWorld() World {
	return World{
		TickInterval:        DefaultTickInterval,
		AutosaveInterval:    DefaultAutosaveInterval,
		DeleteCharAfterDays: DefaultDeleteCharAfterDays,
		MaxRunSpeed:         DefaultMaxRunSpeed,
		SpawnProtection:     DefaultSpawnProtection,
		// General.ini GridNeighborTurnOnTime and GridNeighborTurnOffTime.
		GridTurnOnTime:  Duration(time.Second),
		GridTurnOffTime: Duration(90 * time.Second),
	}
}

// Chat configures the chat channels.
type Chat struct {
	Comment string `json:"_comment,omitempty"`
	// GeneralRange is how far normal chat is heard, in game units (3D).
	GeneralRange int `json:"generalRange"`
	// Shout says who hears shout chat (!), Mobius GlobalChat.
	Shout ChatMode `json:"shout"`
	// Trade says who hears trade chat (+), Mobius TradeChat. Mobius also
	// lets only players of level 20 and up trade-chat.
	Trade ChatMode `json:"trade"`
	// MaxLength is the longest message in characters; longer ones from
	// players below GM level are refused (Mobius Say2).
	MaxLength int `json:"maxLength"`
}

// ChatMode says who hears shout or trade chat: Mobius's ChatBroadcastType,
// written in lower case. The file may use any case.
type ChatMode string

// The chat modes.
const (
	// ChatModeOn sends the message to the players in the speaker's map
	// region (the town area of /loc) and instance. It is Mobius's default.
	ChatModeOn ChatMode = "on"
	// ChatModeGlobal sends the message to every player in the game. Players
	// below GM level may then speak at most every 500 ms (Mobius
	// FloodProtectorGlobalChatInterval).
	ChatModeGlobal ChatMode = "global"
	// ChatModeGM is ChatModeOn for GMs; other players are not heard.
	ChatModeGM ChatMode = "gm"
	// ChatModeOff turns the channel off.
	ChatModeOff ChatMode = "off"
)

// Valid reports whether m is one of the chat modes.
func (m ChatMode) Valid() bool {
	switch m {
	case ChatModeOn, ChatModeGlobal, ChatModeGM, ChatModeOff:
		return true
	}
	return false
}

// UnmarshalText reads a mode in any case, so Mobius's "ON" works too.
func (m *ChatMode) UnmarshalText(b []byte) error {
	*m = ChatMode(strings.ToLower(strings.TrimSpace(string(b))))
	return nil
}

// DefaultChat returns the defaults: Mobius's ranges and limits, with shout
// and trade chat heard in the speaker's map region.
func DefaultChat() Chat {
	return Chat{
		GeneralRange: DefaultChatGeneralRange,
		Shout:        ChatModeOn,
		Trade:        ChatModeOn,
		MaxLength:    DefaultChatMaxLength,
	}
}

