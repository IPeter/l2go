// DefaultPath returns ~/.l2go/config/server.json.
func DefaultPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("config: find home directory: %w", err)
	}
	return filepath.Join(home, ".l2go", "config", "server.json"), nil
}

// Load reads the config file at path. If the file does not exist it returns
// Default() with an empty Path. Any other problem, including invalid JSON
// and unknown fields, is an error. Load does not call Validate.
func Load(path string) (Config, error) {
	data, err := os.ReadFile(filepath.Clean(path))
	if errors.Is(err, fs.ErrNotExist) {
		return Default(), nil
	}
	if err != nil {
		return Config{}, fmt.Errorf("config: %w", err)
	}
	cfg, err := Parse(data)
	if err != nil {
		return Config{}, fmt.Errorf("config: %s: %w", path, err)
	}
	cfg.Path = path
	return cfg, nil
}

// Parse decodes a config file. Fields left out of the file stay at their
// zero value, except the listen addresses, internal networks, scripts
// folder, event timeout and the game rule sections of each game server
// (world, chat, npcs), which get their defaults.
//
// Before decoding, ${NAME} and ${NAME:-default} are replaced with the
// environment variable NAME (or default when NAME is unset or empty). A
// variable that is unset and has no default is an error. Use them inside
// JSON strings, for example "externalIP": "${L2GO_PUBLIC_IP:-127.0.0.1}".
func Parse(data []byte) (Config, error) {
	return parse(data, os.LookupEnv)
}

func parse(data []byte, lookup func(string) (string, bool)) (Config, error) {
	data, err := expandEnv(data, lookup)
	if err != nil {
		return Config{}, fmt.Errorf("parse: %w", err)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	var cfg Config
	if err := dec.Decode(&cfg); err != nil {
		return Config{}, fmt.Errorf("parse: %w", err)
	}
	if _, err := dec.Token(); !errors.Is(err, io.EOF) {
		return Config{}, errors.New("parse: unexpected data after the top-level object")
	}
	cfg.applyDefaults()
	return cfg, nil
}

func (c *Config) applyDefaults() {
	l := &c.LoginServer
	if l.ClientListen == "" {
		l.ClientListen = DefaultClientListen
	}
	if l.GameServerListen == "" {
		l.GameServerListen = DefaultGameServerListen
	}
	if l.InternalNetworks == nil {
		l.InternalNetworks = append([]string(nil), DefaultInternalNetworks...)
	}
	if l.RSAKeyPairs == 0 {
		l.RSAKeyPairs = DefaultRSAKeyPairs
	}
	if l.SessionTTL == 0 {
		l.SessionTTL = DefaultSessionTTL
	}
	for i := range c.GameServers {
		gs := &c.GameServers[i]
		s := &gs.Scripts
		if s.Dir == "" {
			s.Dir = DefaultScriptsDir
		}
		if s.EventTimeout == 0 {
			s.EventTimeout = DefaultEventTimeout
		}
		if gs.AllowedProtocols == nil {
			gs.AllowedProtocols = append([]int32(nil), DefaultAllowedProtocols...)
		}
		if gs.DataDir == "" {
			gs.DataDir = DefaultDataDir
		}
	}
}

// Validate checks the whole configuration and reports every problem found.
func (c Config) Validate() error {
	var errs []error
	add := func(format string, args ...any) {
		errs = append(errs, fmt.Errorf(format, args...))
	}

	l := c.LoginServer
	if l.Host == "" {
		add("loginserver.host is empty")
	}
	if err := checkListen(l.ClientListen); err != nil {
		add("loginserver.clientListen: %w", err)
	}
	if err := checkListen(l.GameServerListen); err != nil {
		add("loginserver.gameServerListen: %w", err)
	}
	for _, n := range l.InternalNetworks {
		if _, err := netip.ParsePrefix(n); err != nil {
			add("loginserver.internalNetworks: %w", err)
		}
	}
	if err := l.Database.validate(); err != nil {
		add("loginserver.database: %w", err)
	}
	if l.RSAKeyPairs < 1 || l.RSAKeyPairs > 100 {
		add("loginserver.rsaKeyPairs: %d is not in 1-100", l.RSAKeyPairs)
	}
	if l.SessionTTL <= 0 {
		add("loginserver.sessionTTL: %v is not positive", time.Duration(l.SessionTTL))
	}

	seen := make(map[int]bool)
	for i, gs := range c.GameServers {
		where := fmt.Sprintf("gameservers[%d]", i)
		if gs.ID < 1 || gs.ID > 255 {
			add("%s.id: %d is not in 1-255", where, gs.ID)
		} else if seen[gs.ID] {
			add("%s.id: %d is used twice", where, gs.ID)
		}
		seen[gs.ID] = true
		if strings.TrimSpace(gs.Name) == "" {
			add("%s.name is empty", where)
		}
		if err := checkIPv4(gs.InternalIP); err != nil {
			add("%s.internalIP: %w", where, err)
		}
		if err := checkIPv4(gs.ExternalIP); err != nil {
			add("%s.externalIP: %w", where, err)
		}
		if err := checkPort(gs.Port); err != nil {
			add("%s.port: %w", where, err)
		}
		if err := gs.Database.validate(); err != nil {
			add("%s.database: %w", where, err)
		}
		if strings.TrimSpace(gs.Scripts.Dir) == "" {
			add("%s.scripts.dir is empty", where)
		}
		if gs.Scripts.EventTimeout <= 0 {
			add("%s.scripts.eventTimeout: %v is not positive", where, time.Duration(gs.Scripts.EventTimeout))
		}
		if strings.TrimSpace(gs.Secret) == "" {
			add("%s.secret is empty", where)
		}
		if len(gs.AllowedProtocols) == 0 {
			add("%s.allowedProtocols is empty", where)
		}
		if strings.TrimSpace(gs.DataDir) == "" {
			add("%s.dataDir is empty", where)
		}
		if gs.MaxCharactersPerAccount < 0 {
			add("%s.maxCharactersPerAccount: %d is negative", where, gs.MaxCharactersPerAccount)
		}
		for _, err := range gs.validateGame() {
			add("%s.%w", where, err)
		}
	}
	if err := errors.Join(errs...); err != nil {
		return fmt.Errorf("config: invalid:\n%w", err)
	}
	return nil
}

// validateGame checks the game rule sections. Each error starts with the
// field path below the game server.
func (g GameServer) validateGame() []error {
	var errs []error
	add := func(format string, args ...any) {
		errs = append(errs, fmt.Errorf(format, args...))
	}
	w := g.World
	if w.TickInterval <= 0 {
		add("world.tickInterval: %v is not positive", time.Duration(w.TickInterval))
	}
	if w.AutosaveInterval < 0 {
		add("world.autosaveInterval: %v is negative", time.Duration(w.AutosaveInterval))
	}
	if w.DeleteCharAfterDays < 0 || w.DeleteCharAfterDays > MaxDeleteCharAfterDays {
		add("world.deleteCharAfterDays: %d is not in 0-%d", w.DeleteCharAfterDays, MaxDeleteCharAfterDays)
	}
	if w.MaxRunSpeed <= 0 {
		add("world.maxRunSpeed: %d is not positive", w.MaxRunSpeed)
	}
	if w.SpawnProtection < 0 {
		add("world.spawnProtection: %v is negative", time.Duration(w.SpawnProtection))
	}
	if g.Chat.GeneralRange <= 0 {
		add("chat.generalRange: %d is not positive", g.Chat.GeneralRange)
	}
	if !g.Chat.Shout.Valid() {
		add("chat.shout: %q is not one of on, global, gm, off", g.Chat.Shout)
	}
	if !g.Chat.Trade.Valid() {
		add("chat.trade: %q is not one of on, global, gm, off", g.Chat.Trade)
	}
	if g.Chat.MaxLength <= 0 {
		add("chat.maxLength: %d is not positive", g.Chat.MaxLength)
	}
	if g.NPCs.MaxFreeTeleportLevel < 0 {
		add("npcs.maxFreeTeleportLevel: %d is negative", g.NPCs.MaxFreeTeleportLevel)
	}
	if g.NPCs.InteractionRange <= 0 {
		add("npcs.interactionRange: %d is not positive", g.NPCs.InteractionRange)
	}
	return errs
}

func (d Database) validate() error {
	if d.Name == "" {
		return errors.New("name is empty")
	}
	if d.URI != "" {
		if !strings.HasPrefix(d.URI, "mongodb://") && !strings.HasPrefix(d.URI, "mongodb+srv://") {
			return errors.New("uri must start with mongodb:// or mongodb+srv://")
		}
		return nil
	}
	if d.Host == "" {
		return errors.New("host is empty (set host and port, or uri)")
	}
	return checkPort(d.Port)
}

func checkPort(p int) error {
	if p < 1 || p > 65535 {
		return fmt.Errorf("port %d is not in 1-65535", p)
	}
	return nil
}

func checkListen(addr string) error {
	_, port, err := net.SplitHostPort(addr)
	if err != nil {
		return err
	}
	p, err := strconv.Atoi(port)
	if err != nil {
		return fmt.Errorf("port %q is not a number", port)
	}
	return checkPort(p)
}

func checkIPv4(s string) error {
	ip, err := netip.ParseAddr(s)
	if err != nil {
		return err
	}
	if !ip.Unmap().Is4() {
		return fmt.Errorf("%s is not an IPv4 address", s)
	}
	return nil
}
