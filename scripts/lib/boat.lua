-- say(a, b, ...) is what the players near either point hear: the messages
-- given (names of M.msg) in order.
function M.say(a, b, ...)
  local ids = {}
  for _, name in ipairs({ ... }) do
    local id = M.msg[name]
    if id == nil then
      error("lib.boat: unknown message " .. tostring(name), 2)
    end
    ids[#ids + 1] = id
  end
  return { near = { a, b }, messages = ids }
end

-- with_horn(say, point) adds the horn at point to an announcement (Mobius
-- broadcastPackets with the PlaySound last).
function M.with_horn(say, point)
  say.horn = point
  return say
end

-- await(dock, a, b, message) waits for a free dock, announcing the delay.
function M.await(dock, a, b, message)
  local busy = M.say(a, b, message)
  busy.dock = dock
  return busy
end

-- route(def) declares a schedule (vehicles.add_route), starting after
-- START_DELAY unless def.start_delay says otherwise.
function M.route(def)
  if def.start_delay == nil then
    def.start_delay = M.START_DELAY
  end
  vehicles.add_route(def)
end

return M
